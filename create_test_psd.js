import fs from 'fs';
import { writePsd } from 'ag-psd';
import 'ag-psd/initialize-canvas.js';
import { createCanvas } from 'canvas';

console.log("Generating sample PSD file for testing...");

// 1. Create a White Background Canvas
const bgCanvas = createCanvas(1200, 800);
const bgCtx = bgCanvas.getContext('2d');
bgCtx.fillStyle = '#ffffff';
bgCtx.fillRect(0, 0, 1200, 800);

// Draw some lines or border on background
bgCtx.strokeStyle = '#e2e8f0';
bgCtx.lineWidth = 10;
bgCtx.strokeRect(20, 20, 1160, 760);

// 2. Create a Visual Image Layer (Indigo Circle)
const circleCanvas = createCanvas(300, 300);
const circleCtx = circleCanvas.getContext('2d');
circleCtx.fillStyle = '#6366f1'; // Indigo
circleCtx.beginPath();
circleCtx.arc(150, 150, 120, 0, 2 * Math.PI);
circleCtx.fill();

// 3. Create a Visual Accent Layer (Orange Rounded Box)
const rectCanvas = createCanvas(200, 100);
const rectCtx = rectCanvas.getContext('2d');
rectCtx.fillStyle = '#f97316'; // Orange
rectCtx.beginPath();
rectCtx.roundRect(0, 0, 200, 100, 16);
rectCtx.fill();

// Define PSD structure
const psd = {
  width: 1200,
  height: 800,
  children: [
    // Background layer
    {
      name: 'Background Base',
      left: 0,
      top: 0,
      right: 1200,
      bottom: 800,
      canvas: bgCanvas
    },
    // Indigo Circle image layer
    {
      name: 'Indigo Circle Shape',
      left: 450,
      top: 300,
      right: 750,
      bottom: 600,
      canvas: circleCanvas
    },
    // Orange Accent shape layer
    {
      name: 'Orange Accent Box',
      left: 850,
      top: 450,
      right: 1050,
      bottom: 550,
      canvas: rectCanvas
    },
    // Large Title text layer
    {
      name: 'Header Title Text',
      left: 100,
      top: 80,
      right: 1100,
      bottom: 160,
      text: {
        text: 'PSD2HTML AI Conversion Engine',
        style: {
          fontName: 'Outfit-Bold',
          fontSize: 48,
          fillColor: { r: 11, g: 15, b: 25, a: 1 }
        }
      }
    },
    // Description text layer
    {
      name: 'Sub-description Text',
      left: 100,
      top: 170,
      right: 1100,
      bottom: 270,
      text: {
        text: 'This is a sample website layout generated completely from programmatic PSD file coordinates.\nThe HTML texts are fully selectable, and graphics are exported as standalone PNG assets.',
        style: {
          fontName: 'PlusJakartaSans-Regular',
          fontSize: 18,
          fillColor: { r: 74, g: 85, b: 104, a: 1 }
        }
      }
    },
    // Footer text layer
    {
      name: 'Footer Text',
      left: 100,
      top: 700,
      right: 1100,
      bottom: 740,
      text: {
        text: 'Generated by PSD2HTML engine version 1.0.0',
        style: {
          fontName: 'FiraCode-Regular',
          fontSize: 13,
          fillColor: { r: 148, g: 163, b: 184, a: 1 }
        }
      }
    }
  ]
};

try {
  const psdBuffer = writePsd(psd);
  fs.writeFileSync('sample_test.psd', Buffer.from(psdBuffer));
  console.log("Successfully created sample_test.psd! (1200x800)");
} catch (e) {
  console.error("Error creating sample PSD:", e);
}
